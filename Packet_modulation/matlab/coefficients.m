clc;
clearvars;
close all;

%% 1. Parameters
OSR  = 8;              % oversampling ratio (samples per symbol)
span = 2;              % filter span in symbols
BT   = 0.5;            % Gaussian BT product

%% generate coefficients
g = gaussdesign(BT, span, OSR);          % span*OSR + 1 = 25 taps, sum(g) = 1

%% Generate gauss_coeff.svh from the Gaussian taps (g from gaussdesign)
W = 16;  F = W-1;
g_int = round(g * 2^F);
N = numel(g_int);

fid = fopen('D:/Files/Documents/bluetooth/GFSK/Verilog_code/project_1.srcs/sources_1/new/gauss_coeff.vh', 'w');
fprintf(fid, '// Auto-generated by MATLAB, do not edit by hand\n');
fprintf(fid, '// BT=%.2f, OSR=%d, span=%d, W=%d, F=%d\n', BT, OSR, span, W, F);
fprintf(fid, 'localparam counter_size = %d;\n', log2(OSR));
fprintf(fid, 'localparam NTAPS = %d;\n', N);
fprintf(fid, 'localparam GEN_W = %d;\n', W);
fprintf(fid, 'reg [W-1:0] coeff [0:NTAPS-1];\n');
fprintf(fid, 'initial begin\n');
for k = 1:N
    fprintf(fid, '  coeff[%d] = %d''d%d;\n', k-1, W, g_int(k));
end
fprintf(fid, 'end\n');
fclose(fid);